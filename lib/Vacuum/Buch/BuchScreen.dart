  /// buch → branch name (company_id / branch / company_name)
  String _branchOf(Map user) {
    final int? id = int.tryParse("${user["company_id"] ?? ""}");
    if (id != null) {
      for (final c in branchCompanies) {
        if (c.id == id) return c.name;
      }
    }
    final dynamic b = user["branch"] ?? user["branch_name"] ?? user["company"];
    if (b is Map && b["name"] != null) return b["name"].toString();
    final String t = (b ?? user["company_name"] ?? "").toString().trim();
    return t.isEmpty || t == "null" ? "" : t;
  }




  void searchUser(String value) {
    if (value.trim().isEmpty) {
      setState(() {
        userlist = List.from(allUsers);
      });
      return;
    }

    final query = value.toLowerCase().trim();

    setState(() {
      userlist = allUsers.where((user) {
        final buchNo = (user["buch_no"] ?? "").toString().toLowerCase();
        final weight = (user["weight"] ?? "").toString().toLowerCase();
        final size = (user["size_inch"] ?? "").toString().toLowerCase();

        return buchNo.contains(query) ||
            weight.contains(query) ||
            size.contains(query);
      }).toList();
    });
  }

