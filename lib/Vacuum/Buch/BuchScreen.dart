  Future<void> category() async {
    final String url = _br(ApiConstants.vacuum_buchs);
    debugPrint("🌐 Vacuum buch URL: $url");

    final response = await ApiHelper().getRequest(url);

    if (!mounted) return;

    if (response == null) {
      AppMessage.error(context, "No response");
      return;
    }

    final data = response.data;

    if (response.statusCode == 200) {
      final List categories = data["data"] ?? [];

      setState(() {
        userlist = categories;
        allUsers = categories;
      });

      AppMessage.success(
        context,
        data["message"] ?? "Data Loaded Successfully",
      );

    } else if (response.statusCode == 202) {

      // Offline
      setState(() {
        userlist = data["data"] ?? [];
        allUsers = data["data"] ?? [];
      });

      AppMessage.success(
        context,
        data["message"] ?? "Offline Mode",
      );

    } else {
      setState(() {
        userlist = [];
        allUsers = [];
      });

      AppMessage.error(context, "Failed to load data");
    }
  }

  Widget buildStatusBadge(Map user) {
    String metal = (user["metal"] ?? "").toString().toLowerCase();

    Color bgColor;
