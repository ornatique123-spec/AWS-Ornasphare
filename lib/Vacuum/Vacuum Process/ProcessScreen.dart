  Future<void> create_user(String name) async {

    /// 🔥 VALIDATION FIRST
    // if (!validateFields()) return;
    try {
      final body = {

        "name": name.toString(),

      };

      print("Login Request: $body");
      print("Login API URL: ${ApiConstants.vacuum_processes}");

      final response = await OfflineApiHelper.instance.postRequest(
        ApiConstants.vacuum_processes,
        body,
      );

      if (response == null) {
        showError("No response from server");
        return;
      }

      final data = response.data;
      print("Login Response: $data");

      // ✅ SUCCESS
      if (response.statusCode == 200 ||
          response.statusCode == 202) {
        if (response.statusCode == 202) {
          AppMessage.success(
            context,
            "No Internet. Update saved offline.",
          );
        }
        // AppMessage.success(
        //   context,
        //   data["message"] ?? "Data Loaded Successfully",
        // );

        category();
        // Navigator.push(
        //   context,
        //   MaterialPageRoute(builder: (_) => Processscreen()),
        // );
      }
      // 🔴 INVALID CREDENTIALS
      else if (response.statusCode == 401) {
        showError(data['message'] ?? "Invalid credentials");
      }
      // 🔴 VALIDATION ERROR
      else if (response.statusCode == 422) {
        String errorMessage = "";

        if (data['errors'] != null) {
          Map<String, dynamic> errors = data['errors'];

          errors.forEach((key, value) {
            errorMessage += "${value[0]}\n";
          });
        } else {
          errorMessage = data['message'] ?? "Validation error";
        }

        showError(errorMessage);
      }
      // 🔴 OTHER ERRORS
      else {
        showError(data['message'] ?? "Server error (${response.statusCode})");
      }
    } catch (e) {
      print("Login Exception: $e");
      showError("Something went wrong. Please try again.");
    }
  }

