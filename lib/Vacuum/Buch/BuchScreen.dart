  Future<void> _showWeightHistoryDialog(Map user) async {
    final int id =
        int.tryParse(user["id"]?.toString() ?? "0") ?? 0;

    if (id <= 0) {
      _showErrorMessage("Invalid Buch ID");
      return;
    }



    try {
      final response = await ApiHelper().getRequest(
        "${ApiConstants.baseUrl}vacuum-buchs/$id/weight-history",
      );

      if (!context.mounted) return;

      debugPrint("================================");
      debugPrint("WEIGHT HISTORY");
      debugPrint("BUCH ID: $id");
      debugPrint("RESPONSE: ${response?.data}");
      debugPrint("================================");

      if (response == null) {
        _showErrorMessage("No response from server");
        return;
      }

      final responseData = response.data;

      if (responseData["success"] == true) {
        final List history =
        responseData["data"] is List
            ? responseData["data"]
            : [];

        _showWeightHistoryPopup(
          user: user,
          history: history,
        );
      } else {
        _showErrorMessage(
          responseData["message"]?.toString() ??
              "No weight history found",
        );
      }
    } catch (e) {
      debugPrint("Weight History API Error: $e");

      _showErrorMessage(
        "Unable to load weight history",
      );
    }
  }
